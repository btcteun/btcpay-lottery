@app.route("/api/verify", methods=["POST"])
def api_verify():
    """Organizer types the verification code (or preimage) shown by the winner;
    server answers match / no match. Both are compared by SHA-256, constant time."""
    if _rate_limited(request.remote_addr):
        return jsonify({"error": "too many attempts, wait 10 minutes"}), 429
    payload = request.get_json(silent=True) or {}
    if not _admin_ok(payload):
        return jsonify({"error": "invalid token"}), 403
    claimed = str(payload.get("code", payload.get("preimage", ""))).strip()
    prize = _prize_from(payload)
    if prize is None:
        return jsonify({"error": "no winner yet / unknown prize"}), 400
    with _lock:
        inv_id = invoice_for_ticket(STATE, prize["ticket"])
        rec = STATE["invoices"][inv_id]
        stored = [h for h in (rec.get("verification_sha256"), rec.get("preimage_sha256")) if h]
    if not stored:
        return jsonify({"error": "no verification code or preimage on record for this ticket "
                                 "(POS sale?); check the invoice in BTCPay by hand"}), 409
    candidates = {claimed, claimed.lower()}
    ok = any(hmac.compare_digest(_sha256(c), h) for c in candidates for h in stored)
    if ok:
        with _lock:
            for p in STATE["winner"]["prizes"]:
                if p["prize"] == prize["prize"]:
                    p["claimed"] = True
            _save(STATE)
        print(f"[claim] prize {prize['prize']} claimed by ticket {prize['ticket']}")
    else:
        print(f"[claim] prize {prize['prize']}: verification failed")
    return jsonify({"match": ok, "prize": prize["prize"]})


