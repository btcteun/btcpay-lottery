def commitment_of(tickets: list) -> str:
    return hashlib.sha256(",".join(tickets).encode()).hexdigest()


def draw(tickets: list, block_hash: str, prize_count: int = 1, backup_count: int = 0) -> list:
    """
    Draw up to `prize_count` winners plus `backup_count` stand-ins from one block.
    Round n:  SHA256(blockhash + "," + <frozen sorted list> + "," + n)  mod  <remaining tickets>
    The winning ticket is removed from the pool before the next round; other
    tickets of the same buyer stay in. The frozen list in the hash input never
    changes, so anyone can replay every round with just the block hash.
    Rounds 1..prize_count are prizes; rounds after that are backups, in order.
    """
    frozen = sorted(tickets)
    pool = list(frozen)
    results = []
    for n in range(1, min(prize_count + backup_count, len(frozen)) + 1):
        hash_input = block_hash + "," + ",".join(frozen) + "," + str(n)
        digest = hashlib.sha256(hash_input.encode()).hexdigest()
        idx = int(digest, 16) % len(pool)
        ticket = pool.pop(idx)
        entry = {
            "prize": n,
            "label": PRIZE_LABELS[n - 1] if n - 1 < len(PRIZE_LABELS) else f"Prize {n}",
            "hash_input": hash_input,
            "sha256": digest,
            "index": idx,
            "pool_size": len(pool) + 1,
            "ticket": ticket,
            "claimed": False,
        }
        if n > prize_count:
            entry["backup"] = n - prize_count
            entry["label"] = f"Backup {n - prize_count}"
            entry["used_for"] = None
        results.append(entry)
    return results


def forfeit_prize(state, prize_no: int):
    """Winner didn't show: hand prize `prize_no` to the next unused backup ticket.
    Returns (prize entry, error message). Caller must hold _lock."""
    w = state.get("winner")
    if not w:
        return None, "no winner yet"
    prize = next((p for p in w["prizes"] if p["prize"] == prize_no), None)
    if prize is None:
        return None, "unknown prize"
    if prize.get("claimed"):
        return None, "this prize was already claimed"
    backup = next((b for b in w.get("backups", []) if b.get("used_for") is None), None)
    if backup is None:
        return None, "no backup tickets left"
    prize.setdefault("forfeited", []).append(prize["ticket"])
    prize["ticket"] = backup["ticket"]
    prize["from_backup"] = backup["backup"]
    backup["used_for"] = prize_no
    return prize, None


def invoice_for_ticket(state, ticket_id: str):
    for inv_id, inv in state["invoices"].items():
        if ticket_id in inv["ticket_ids"]:
            return inv_id
    return None


def background_loop():
    with _lock:
        phase = STATE["phase"]
    if phase in ("winner", "no_entries"):
        # Draw already done (container restart): never redraw, it would wipe claims/forfeits.
        print(f"[draw] state file already in phase '{phase}', nothing to do")
        return
    if phase == "drawing" and STATE.get("commitment"):
        # Restarted while waiting for the block: keep the frozen list, just finish the draw.
        print("[draw] resuming: list already frozen, waiting for the drawing block")
        _finish_draw(all_ticket_ids(STATE))
        return
    while time.time() < END_UNIX:
        if time.time() >= START_UNIX:
            sync_invoices()
        time.sleep(POLL_INTERVAL_INVOICES)

    sync_invoices()  # final sweep for invoices created before END_TIME
    with _lock:
        tickets = all_ticket_ids(STATE)
        STATE["phase"] = "drawing"
        STATE["commitment"] = {
            "ticket_count": len(tickets),
            "prize_count": PRIZE_COUNT,
            "backup_count": BACKUP_COUNT,
            "sha256_of_ticket_list": commitment_of(tickets),
            "rule": "first Bitcoin block with timestamp >= END_TIME; round n = "
                    "SHA256(blockhash,list,n) mod remaining tickets, drawn ticket removed; "
                    f"rounds 1-{PRIZE_COUNT} are prizes, later rounds are backups in order",
            "end_time": END_TIME,
        }
        _save(STATE)
    print(f"[draw] sales closed, {len(tickets)} tickets frozen, commitment published")

    _finish_draw(tickets)


def _finish_draw(tickets: list):
    if not tickets:
        with _lock:
            STATE["phase"] = "no_entries"
            _save(STATE)
        return

    blk = wait_for_drawing_block(int(END_UNIX))
    drawn = draw(tickets, blk["hash"], PRIZE_COUNT, BACKUP_COUNT)
    winners = [d for d in drawn if "backup" not in d]
    backups = [d for d in drawn if "backup" in d]
    with _lock:
        STATE["winner"] = {
            "block_height": blk["height"],
            "block_hash": blk["hash"],
            "block_timestamp": blk["timestamp"],
            "ticket_list": tickets,
            "prizes": winners,
            "backups": backups,
        }
        STATE["phase"] = "winner"
        _save(STATE)
    for w in drawn:
        print(f"[draw] {w['label']}: {w['ticket']} (block {blk['height']})")


