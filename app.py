def _btcpay_get(path: str, params: dict = None):
    url = f"{BTCPAY_URL}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params, doseq=True)
    req = urllib.request.Request(url, headers={"Authorization": f"token {BTCPAY_API_KEY}", "User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.loads(r.read().decode())


def _btcpay_post(path: str, body: dict):
    req = urllib.request.Request(
        f"{BTCPAY_URL}{path}",
        data=json.dumps(body).encode(),
        headers={"Authorization": f"token {BTCPAY_API_KEY}", "Content-Type": "application/json", "User-Agent": USER_AGENT},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.loads(r.read().decode())


def create_ticket_invoice(count: int, order_id: str) -> dict:
    """Create a BTCPay invoice for `count` tickets. Returns {"id", "checkoutLink"}.
    order_id = "<ticket id>-<verification code>", sent as orderId and as the memo (itemDesc).
    API key needs the btcpay.store.cancreateinvoice permission."""
    body = {
        "amount": str(count * TICKET_PRICE_SATS),
        "currency": "SATS",
        "metadata": {"orderId": order_id, "itemDesc": order_id, "ticketCount": count},
        "checkout": {
            # {InvoiceId}, not {OrderId}: the orderId carries the verification code and
            # the redirect URL ends up in BTCPay/browser/proxy logs.
            "redirectURL": f"{PUBLIC_URL}/?invoice={{InvoiceId}}",
            "redirectAutomatically": True,
        },
    }
    inv = _btcpay_post(f"/api/v1/stores/{BTCPAY_STORE_ID}/invoices", body)
    return {"id": inv["id"], "checkoutLink": inv["checkoutLink"]}


def fetch_invoice(invoice_id: str) -> dict:
    return _btcpay_get(f"/api/v1/stores/{BTCPAY_STORE_ID}/invoices/{invoice_id}")


def fetch_settled_invoices_in_window():
    """All Settled invoices created in [START, END], with pagination."""
    out, skip, take = [], 0, 100
    while True:
        page = _btcpay_get(
            f"/api/v1/stores/{BTCPAY_STORE_ID}/invoices",
            {
                "startDate": int(START_UNIX),
                "endDate": int(END_UNIX),
                "status": ["Settled"],
                "skip": skip,
                "take": take,
            },
        )
        out.extend(page)
        if len(page) < take:
            return out
        skip += take


def fetch_invoice_preimage(invoice_id: str):
    """
    Locate the Lightning preimage in the payment-methods response.
    Field names vary by BTCPay version — verify with:
      curl -H "Authorization: token $KEY" \
        $BTCPAY_URL/api/v1/stores/$STORE/invoices/$ID/payment-methods
    """
    methods = _btcpay_get(f"/api/v1/stores/{BTCPAY_STORE_ID}/invoices/{invoice_id}/payment-methods")
    for m in methods:
        pm = (m.get("paymentMethodId") or m.get("paymentMethod") or "").lower()
        if "ln" not in pm and "lightning" not in pm:
            continue
        # BTCPay 2.x: preimage lives in additionalData on the payment method
        extra = m.get("additionalData") or {}
        if isinstance(extra, dict) and extra.get("preimage"):
            return extra["preimage"]
        # Older versions: inside each payment entry
        for p in m.get("payments", []):
            for key in ("preimage", "paymentProof"):
                v = p.get(key)
                if v:
                    return v
            details = p.get("details") or {}
            if isinstance(details, dict):
                for key in ("preimage", "paymentProof"):
                    if details.get(key):
                        return details[key]
    return None


def ticket_count_from_invoice(inv: dict) -> int:
    """Derive ticket count from amount paid, in sats. Never trust metadata."""
    amount = float(inv.get("amount", 0))
    currency = (inv.get("currency") or "").upper()
    if currency == "SATS":
        sats = amount
    elif currency == "BTC":
        sats = amount * 100_000_000
    else:
        # Fiat-priced tickets: convert via your own fixed rule, or price in SATS.
        # Refusing here is safer than guessing.
        return 0
    count = int(sats // TICKET_PRICE_SATS)
    return max(0, min(count, MAX_TICKETS_PER_INVOICE))


def _resolve_ticket_id(state, inv: dict) -> tuple:
    """(ticket id, verification code) from the orderId this app put on the invoice.
    POS sales (no orderId) or a collision with an already settled invoice get a
    fresh ticket ID and no verification code. Caller must hold _lock."""
    inv_id = inv["id"]
    tid, code = split_order_id((inv.get("metadata") or {}).get("orderId"))
    pending = state.setdefault("pending", {})
    if tid:
        taken = any(o.get("ticket_id") == tid for o in state["invoices"].values())
        reserved_for_other = tid in pending and pending[tid] != inv_id
        if not taken and not reserved_for_other:
            pending.pop(tid, None)
            return tid, code
        print(f"[sync] ticket id {tid} on invoice {inv_id} already used, regenerating")
    return new_ticket_id(state), None


def ingest_invoice(inv: dict) -> bool:
    """Register a settled invoice as tickets. Returns True if (now) registered."""
    inv_id = inv["id"]
    with _lock:
        if inv_id in STATE["invoices"]:
            return True
        if STATE["phase"] != "sales":
            return False
    if inv.get("status") not in ("Settled",):
        return False
    created = inv.get("createdTime")
    if created is not None and not (START_UNIX <= float(created) <= END_UNIX):
        return False
    try:
        preimage = fetch_invoice_preimage(inv_id)
    except Exception as e:
        print(f"[sync] preimage lookup failed for {inv_id}: {e}")
        return False
    if not preimage:
        # BTCPay sometimes reports a settled Lightning payment with preimage null.
        # The buyer paid, so register the tickets; the preimage is retried each poll.
        print(f"[sync] {inv_id}: settled but BTCPay returned no preimage (yet), registering anyway")
    count = ticket_count_from_invoice(inv)
    if count == 0:
        print(f"[sync] {inv_id} paid below ticket price / unknown currency, skipped")
        return False
    with _lock:
        if STATE["phase"] != "sales":
            return False
        tid, code = _resolve_ticket_id(STATE, inv)
        STATE["invoices"][inv_id] = {
            "ticket_id": tid,
            "ticket_ids": ticket_ids_for(tid, count),
            "verification_sha256": _sha256(code) if code else None,
            "preimage_sha256": _sha256(preimage) if preimage else None,
            "preimage": preimage,
            "created": created,
        }
        _save(STATE)
        print(f"[sync] {inv_id}: {count} ticket(s)")
    return True


def sync_invoices():
    try:
        invoices = fetch_settled_invoices_in_window()
    except Exception as e:  # network / auth / JSON errors
        print(f"[sync] failed: {e}")
        return
    for inv in invoices:
        ingest_invoice(inv)
    retry_missing_preimages()


def retry_missing_preimages():
    """Fill in preimages for registered invoices where BTCPay had none at ingest time."""
    with _lock:
        missing = [i for i, o in STATE["invoices"].items() if not o.get("preimage")]
    for inv_id in missing:
        try:
            preimage = fetch_invoice_preimage(inv_id)
        except Exception as e:
            print(f"[sync] preimage retry failed for {inv_id}: {e}")
            continue
        if not preimage:
            continue
        with _lock:
            STATE["invoices"][inv_id]["preimage"] = preimage
            STATE["invoices"][inv_id]["preimage_sha256"] = hashlib.sha256(preimage.encode()).hexdigest()
            _save(STATE)
        print(f"[sync] {inv_id}: preimage arrived")


