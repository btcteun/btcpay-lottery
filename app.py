def parse_iso(s: str) -> float:
    return datetime.fromisoformat(s).timestamp()


START_UNIX = parse_iso(START_TIME)
END_UNIX = parse_iso(END_TIME)


def _used_ticket_ids(state) -> set:
    """Every base ticket ID in the state file: settled invoices and unpaid pending ones."""
    used = {inv["ticket_id"] for inv in state["invoices"].values() if inv.get("ticket_id")}
    used.update(state.get("pending", {}).keys())
    return used


def new_ticket_id(state) -> str:
    """Random 7-char ID (A-Z, a-z, 0-9); regenerated until it is not already in the state.
    Caller must hold _lock."""
    used = _used_ticket_ids(state)
    while True:
        tid = "".join(secrets.choice(TICKET_ID_ALPHABET) for _ in range(TICKET_ID_LENGTH))
        if tid not in used:
            return tid


def is_valid_ticket_id(tid) -> bool:
    return (isinstance(tid, str) and len(tid) == TICKET_ID_LENGTH
            and all(c in TICKET_ID_ALPHABET for c in tid))


def new_verification_code() -> str:
    return "".join(secrets.choice("0123456789") for _ in range(VERIFICATION_CODE_LENGTH))


def is_valid_verification_code(code) -> bool:
    return isinstance(code, str) and len(code) == VERIFICATION_CODE_LENGTH and code.isdigit()


def order_id_for(ticket_id: str, code: str) -> str:
    return f"{ticket_id}-{code}"


def split_order_id(order_id) -> tuple:
    """"Kq7zR2x-48213" -> ("Kq7zR2x", "48213"); "Kq7zR2x" -> ("Kq7zR2x", None); junk -> (None, None)."""
    if not isinstance(order_id, str):
        return None, None
    tid, _, code = order_id.strip().partition("-")
    if not is_valid_ticket_id(tid):
        return None, None
    return tid, (code if is_valid_verification_code(code) else None)


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def ticket_ids_for(ticket_id: str, count: int) -> list:
    """One ticket keeps the bare ID; several tickets on one invoice get -1, -2, …"""
    if count == 1:
        return [ticket_id]
    return [f"{ticket_id}-{i + 1}" for i in range(count)]


def all_ticket_ids(state) -> list:
    out = []
    for inv in state["invoices"].values():
        out.extend(inv["ticket_ids"])
    return sorted(out)


