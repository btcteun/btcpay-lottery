# Very small in-memory rate limiter for admin endpoints: 10 attempts / 10 min / IP
_attempts = defaultdict(list)


def _rate_limited(ip: str, limit=10, window=600) -> bool:
    """Per endpoint + client IP, so a buyer's lookups don't eat the organizer's verify budget."""
    key = f"{request.endpoint}:{ip}"
    now = time.time()
    _attempts[key] = [t for t in _attempts[key] if now - t < window]
    if len(_attempts[key]) >= limit:
        return True
    _attempts[key].append(now)
    return False


def _prize_from(payload: dict):
    """Look up the prize entry (default: prize 1) from the stored draw."""
    try:
        n = int(payload.get("prize", 1))
    except (TypeError, ValueError):
        return None
    with _lock:
        w = STATE["winner"]
        if not w:
            return None
        for p in w["prizes"]:
            if p["prize"] == n:
                return dict(p)
    return None


def _admin_ok(payload: dict) -> bool:
    token = str(payload.get("token", ""))
